class ActionRegistry:
    """Centralized, strictly allowlisted action registry."""

    def __init__(self):
        self._registry: Dict[str, ActionDefinition] = {}
        self._register_default_actions()

    def _register_default_actions(self):
        self.register(
            ActionDefinition(
                action_type="create_incident",
                description="Creates an Incident for investigation from an Alert.",
                risk_level=RiskLevel.LOW,
                required_permission=Permission.INCIDENTS_CREATE,
                execution_handler=handle_create_incident,
                verification_handler=verify_create_incident,
                supports_dry_run=True,
            )
        )
        self.register(
            ActionDefinition(
                action_type="update_incident",
                description="Updates the status or details of an existing Incident.",
                risk_level=RiskLevel.LOW,
                required_permission=Permission.INCIDENTS_UPDATE,
                execution_handler=handle_update_incident,
                supports_dry_run=True,
            )
        )
        self.register(
            ActionDefinition(
                action_type="notify_security_team",
                description="Sends an alert notification to the SOC security team.",
                risk_level=RiskLevel.LOW,
                required_permission=Permission.RESPONSES_EXECUTE,
                execution_handler=handle_notify_security_team,
                supports_dry_run=True,
            )
        )
        self.register(
            ActionDefinition(
                action_type="enrich_event",
                description="Enriches event telemetry with threat intelligence and geo data.",
                risk_level=RiskLevel.LOW,
                required_permission=Permission.RESPONSES_EXECUTE,
                execution_handler=handle_enrich_event,
                supports_dry_run=True,
            )
        )
        self.register(
            ActionDefinition(
                action_type="quarantine_simulation",
                description="Simulates host or container network isolation.",
                risk_level=RiskLevel.HIGH,
                required_permission=Permission.RESPONSES_EXECUTE,
                execution_handler=handle_quarantine_simulation,
                supports_dry_run=True,
            )
        )
        self.register(
            ActionDefinition(
                action_type="account_lock_simulation",
                description="Simulates locking a compromised user account and terminating active sessions.",
                risk_level=RiskLevel.HIGH,
                required_permission=Permission.RESPONSES_EXECUTE,
                execution_handler=handle_account_lock_simulation,
                supports_dry_run=True,
            )
        )
        self.register(
            ActionDefinition(
                action_type="network_block_simulation",
                description="Simulates blocking an offending IP address on boundary firewalls.",
                risk_level=RiskLevel.CRITICAL,
                required_permission=Permission.RESPONSES_EXECUTE,
                execution_handler=handle_network_block_simulation,
                supports_dry_run=True,
            )
        )

    def register(self, action_def: ActionDefinition):
        self._registry[action_def.action_type] = action_def

    def get(self, action_type: str) -> Optional[ActionDefinition]:
        return self._registry.get(action_type)

    def is_registered(self, action_type: str) -> bool:
        return action_type in self._registry

    def list_actions(self) -> List[Dict[str, Any]]:
        return [
            {
                "action_type": a.action_type,
                "description": a.description,
                "risk_level": a.risk_level.value,
                "required_permission": a.required_permission.value,
                "supports_dry_run": a.supports_dry_run,
            }
            for a in self._registry.values()
        ]


action_registry = ActionRegistry()
