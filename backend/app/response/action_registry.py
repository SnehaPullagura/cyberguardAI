def handle_create_incident(db: Session, config: Dict[str, Any], context: Dict[str, Any], mode: ResponseMode) -> Dict[str, Any]:
    """Safe adapter: Creates an Incident for correlated high/critical alerts."""
    from app.models.incident import Incident, IncidentAlert
    from app.models.alert import Alert

    alert_id = context.get("alert_id")
    title = config.get("title") or f"Automated Incident: {context.get('alert_title', 'High Risk Security Event')}"
    severity = config.get("severity") or context.get("severity", "high")
    risk_score = float(context.get("risk_score", 75.0))

    if mode == ResponseMode.DRY_RUN:
        return {
            "success": True,
            "simulated": True,
            "action": "create_incident",
            "predicted_incident": {
                "title": title,
                "severity": severity,
                "risk_score": risk_score,
            },
            "message": "[DRY_RUN] Would create Incident record."
        }

    # Simulation or Authorized Execution creates a structured Incident
    incident_uuid = str(uuid.uuid4())
    inc_code = f"INC-{uuid.uuid4().hex[:8].upper()}"
    new_inc = Incident(
        id=incident_uuid,
        incident_id=inc_code,
        title=title,
        description=f"Auto-generated by playbook response for alert {alert_id or 'N/A'}.",
        severity=severity.lower(),
        status="new",
        risk_score=risk_score,
        created_at=datetime.utcnow(),
        updated_at=datetime.utcnow(),
    )
    db.add(new_inc)
    db.flush()

    if alert_id:
        # Link alert if exists
        alert = db.query(Alert).filter(Alert.id == alert_id).first()
        if alert:
            inc_alert = IncidentAlert(incident_id=new_inc.id, alert_id=alert.id)
            db.add(inc_alert)

    db.commit()
    db.refresh(new_inc)

    return {
        "success": True,
        "action": "create_incident",
        "incident_id": new_inc.incident_id,
        "id": new_inc.id,
        "severity": new_inc.severity,
        "risk_score": new_inc.risk_score,
        "status": new_inc.status,
    }


def verify_create_incident(result: Dict[str, Any], context: Dict[str, Any]) -> bool:
    if result.get("simulated"):
        return True
    return bool(result.get("incident_id") and result.get("success"))


def handle_update_incident(db: Session, config: Dict[str, Any], context: Dict[str, Any], mode: ResponseMode) -> Dict[str, Any]:
    """Safe adapter: Updates status or notes on an existing Incident."""
    from app.models.incident import Incident

    incident_id = context.get("incident_id") or config.get("incident_id")
    new_status = config.get("status", "investigating")

    if mode == ResponseMode.DRY_RUN:
        return {
            "success": True,
            "simulated": True,
            "action": "update_incident",
            "message": f"[DRY_RUN] Would update incident {incident_id} status to {new_status}"
        }

    if not incident_id:
        return {"success": False, "error": "No incident_id specified for update_incident action."}

    inc = db.query(Incident).filter((Incident.id == incident_id) | (Incident.incident_id == incident_id)).first()
    if not inc:
        return {"success": False, "error": f"Incident {incident_id} not found."}

    inc.status = new_status
    inc.updated_at = datetime.utcnow()
    db.commit()
    db.refresh(inc)

    return {
        "success": True,
        "action": "update_incident",
        "incident_id": inc.incident_id,
        "new_status": inc.status,
    }


def handle_notify_security_team(db: Session, config: Dict[str, Any], context: Dict[str, Any], mode: ResponseMode) -> Dict[str, Any]:
    """Safe adapter: Formats and records a security team notification."""
    channel = config.get("channel", "soc-alerts-internal")
    message = config.get("message") or f"Alert notification: {context.get('alert_title', 'Playbook Triggered')} (Risk: {context.get('risk_score', 'N/A')})"

    logger.info(f"[RESPONSE NOTIFY] Channel: {channel} | Message: {message} | Mode: {mode}")

    return {
        "success": True,
        "action": "notify_security_team",
        "channel": channel,
        "delivered_at": datetime.utcnow().isoformat(),
        "simulated": mode in [ResponseMode.DRY_RUN, ResponseMode.SIMULATION],
        "message": message,
    }


def handle_enrich_event(db: Session, config: Dict[str, Any], context: Dict[str, Any], mode: ResponseMode) -> Dict[str, Any]:
    """Safe adapter: Enriches event details with simulated reputation and geolocation context."""
    source_ip = context.get("source_ip") or config.get("target_ip", "192.168.1.100")
    
    # Safe deterministic threat enrichment metadata
    is_private = source_ip.startswith("10.") or source_ip.startswith("192.168.") or source_ip.startswith("172.16.")
    enrichment_data = {
        "target_ip": source_ip,
        "ip_type": "private_rfc1918" if is_private else "public_routable",
        "threat_reputation_score": 15.0 if is_private else 85.0,
        "enrichment_source": "internal_telemetry_intel",
        "autonomous_system": "AS-INTERNAL" if is_private else "AS-EXTERNAL-THREAT",
        "enriched_at": datetime.utcnow().isoformat(),
    }

    return {
        "success": True,
        "action": "enrich_event",
        "enrichment": enrichment_data,
        "simulated": True,
    }


