import logging
import uuid
from typing import Dict, Any, Callable, Optional, List
from datetime import datetime
from sqlalchemy.orm import Session

from app.response.enums import RiskLevel, ResponseMode
from app.security.rbac import Permission

logger = logging.getLogger(__name__)


class ActionDefinition:
    """Definition of an allowlisted response action."""

    def __init__(
        self,
        action_type: str,
        description: str,
        risk_level: RiskLevel,
        required_permission: Permission,
        execution_handler: Callable,
        verification_handler: Optional[Callable] = None,
        supports_dry_run: bool = True,
    ):
        self.action_type = action_type
        self.description = description
        self.risk_level = risk_level
        self.required_permission = required_permission
        self.execution_handler = execution_handler
        self.verification_handler = verification_handler or self._default_verify
        self.supports_dry_run = supports_dry_run

    def _default_verify(self, result: Dict[str, Any], context: Dict[str, Any]) -> bool:
        return result.get("success", False)


